def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when a bundled stub differs from the generated contract")
    args = parser.parse_args()
    stale = []
    files = {PACKAGE / name: text for name, text in generated_files().items()}
    files.update({PUBLIC_PACKAGE / name: text for name, text in public_facade_stubs().items()})
    for destination, text in files.items():
        if args.check:
            if not destination.is_file() or destination.read_text(encoding="utf-8") != text:
                stale.append(destination.relative_to(ROOT).as_posix())
        else:
            destination.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("Regenerate component stubs with python tools/generate_component_stubs.py: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Component type stubs " + ("match the shared schema" if args.check else "generated"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
