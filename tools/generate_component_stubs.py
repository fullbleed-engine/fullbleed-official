_StyleValue: TypeAlias = _StyleAtom | Sequence[_StyleValue]
_StyleInput: TypeAlias = Style | Mapping[str, _StyleValue | None] | Literal[False] | None
_ThemeValue: TypeAlias = str | _Number | Length

