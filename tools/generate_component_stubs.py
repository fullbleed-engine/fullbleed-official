"""Generate experimental component stubs from the shared authoring vocabulary.

This generator needs only Python's standard library. It does not load the engine,
read fonts, or import the Fullbleed package. Run with --check in CI.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import runpy
import sys

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "python/fullbleed/ui/experimental"
SCHEMA = runpy.run_path(str(PACKAGE / "_schema.py"))
HEADER = "# SPDX-License-Identifier: MIT\n# Generated by tools/generate_component_stubs.py; do not edit.\n"


def literal(name):
    return "Literal[" + ", ".join(repr(value) for value in SCHEMA[name]) + "]"


def style_signature(name, prefix, result, indent=""):
    properties = sorted(name.replace("-", "_") for name in SCHEMA["STYLE_PROPERTIES"])
    lines = [f"{indent}def {name}(", f"{indent}    {prefix},"]
    lines.extend(f"{indent}    {prop}: _StyleValue | None = ...," for prop in properties)
    lines.append(f"{indent}) -> {result}: ...")
    return "\n".join(lines)


def generated_files():
    style = HEADER + '''from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from typing import Any, TypeAlias

_Number: TypeAlias = int | float | Decimal
_StyleAtom: TypeAlias = str | _Number | Length | Token
_StyleValue: TypeAlias = _StyleAtom | Sequence[_StyleValue]
_StyleInput: TypeAlias = Style | Mapping[str, _StyleValue | None] | None
_ThemeValue: TypeAlias = str | _Number | Length

class AuthoringError(ValueError):
    message: str
    code: str
    path: tuple[str, ...]
    def __init__(self, message: str, *, code: str = ..., path: Iterable[str] = ...) -> None: ...
    def at(self, name: str) -> AuthoringError: ...
    def to_dict(self) -> dict[str, Any]: ...

@dataclass(frozen=True)
class Length:
    value: _Number
    unit: str
    def __str__(self) -> str: ...

def pt(value: _Number) -> Length: ...
def mm(value: _Number) -> Length: ...
def pct(value: _Number) -> Length: ...

@dataclass(frozen=True)
class Token:
    name: str

def token(name: str) -> Token: ...

@dataclass(frozen=True, init=False)
class Style:
    entries: tuple[tuple[str, object], ...]
'''
    style += style_signature("__init__", "self, *fragments: _StyleInput", "None", "    ")
    style += "\n    def resolve(self, theme: Theme) -> str: ...\n\n"
    style += style_signature("style", "*fragments: _StyleInput", "Style")
    style += '''

def css(declarations: str) -> Style: ...

@dataclass(frozen=True, init=False)
class Theme:
    values: tuple[tuple[str, object], ...]
    text: Style
    def __init__(self, values: Mapping[str, _ThemeValue] | None = ..., *, text: _StyleInput = ...) -> None: ...
    def with_values(self, /, *mappings: Mapping[str, _ThemeValue], **values: _ThemeValue) -> Theme: ...
'''

    tree = HEADER + '''from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from decimal import Decimal
from typing import Literal, ParamSpec, Protocol, TypeAlias, overload
from ._style import Style, _StyleInput, _StyleValue

P = ParamSpec("P")
_Child: TypeAlias = Node | str | int | float | Decimal | None | Iterable[_Child]
_FlowChild: TypeAlias = Node | bool | None | Iterable[_FlowChild]
_Attribute: TypeAlias = str | bool | int | float | Decimal | None
_Attributes: TypeAlias = Mapping[str, _Attribute] | None

@dataclass(frozen=True)
class Node:
    tag: str | None
    children: tuple[_Child, ...] = ...
    attributes: tuple[tuple[str, _Attribute], ...] = ...
    style: Style = ...
    part: str | None = ...
    name: str | None = ...
    source: tuple[str, int] | None = ...
    boundary: bool = ...
    declared_parts: tuple[str, ...] | None = ...
    @property
    def required_tokens(self) -> tuple[str, ...]: ...
    @property
    def parts(self) -> tuple[str, ...]: ...
'''
    tree += style_signature("with_style", "self, *fragments: _StyleInput", "Node", "    ")
    tree += "\n    def with_parts(self, **overrides: _StyleInput) -> Node: ...\n\n"
    props = "style: _StyleInput = ..., class_name: str | None = ..., attrs: _Attributes = ..., part: str | None = ..."
    for name in SCHEMA["PRIMITIVE_TAGS"]:
        tree += f"def {name}(*children: _Child, {props}) -> Node: ...\n"
    tree += f'''
def Fragment(*children: _Child) -> Node: ...
def Heading(*children: _Child, level: int = ..., keep_with_next: bool | None = ..., {props}) -> Node: ...
def Stack(*children: _Child, gap: _StyleValue | None = ..., align: {literal("ALIGNMENTS")} | None = ..., {props}) -> Node: ...
def Row(*children: _Child, gap: _StyleValue | None = ..., align: {literal("ALIGNMENTS")} | None = ..., justify: {literal("JUSTIFICATIONS")} | None = ..., {props}) -> Node: ...
def Flow(*children: _FlowChild, gap: _StyleValue | None = ..., {props}) -> Node: ...
def Grid(*children: _Child, columns: int | str | None = ..., gap: _StyleValue | None = ..., {props}) -> Node: ...
def Image(*, src: str, alt: str, {props}) -> Node: ...
def PageBreak() -> Node: ...

class ComponentFactory(Protocol[P]):
    @property
    def parts(self) -> tuple[str, ...] | None: ...
    def __call__(self, *args: P.args, **kwargs: P.kwargs) -> Node: ...

@overload
def component(fn: Callable[P, Node], *, parts: Iterable[str] | None = ...) -> ComponentFactory[P]: ...
@overload
def component(fn: None = ..., *, parts: Iterable[str] | None = ...) -> Callable[[Callable[P, Node]], ComponentFactory[P]]: ...

'''
    tree += style_signature("styled", "factory: Callable[P, Node], *fragments: _StyleInput", "ComponentFactory[P]")
    tree += f'''

def _element(tag: str, children: Iterable[_Child], *, base: _StyleInput = ..., {props}) -> Node: ...
def _children(values: _Child) -> tuple[_Child, ...]: ...
'''

    table = HEADER + f'''from collections.abc import Callable, Iterable
from dataclasses import dataclass
from typing import Generic, Literal, Protocol, TypeVar
from ._style import Length, _StyleInput
from ._tree import Node, _Attributes, _Child

T = TypeVar("T")

@dataclass(frozen=True)
class Column(Generic[T]):
    label: str
    cell: Callable[[T], _Child]
    align: {literal("COLUMN_ALIGNMENTS")} = ...
    width: Length | None = ...

class _TableFactory(Protocol):
    @property
    def parts(self) -> tuple[str, ...]: ...
    def __call__(self, rows: Iterable[T], *, columns: Iterable[Column[T]],
                 caption: _Child = ..., empty: _Child = ..., repeat_header: bool = ...,
                 row_break: {literal("ROW_BREAKS")} = ..., style: _StyleInput = ...,
                 class_name: str | None = ..., attrs: _Attributes = ...) -> Node: ...

DataTable: _TableFactory
'''

    document = HEADER + '''from collections.abc import Iterable
from dataclasses import dataclass
from os import PathLike
from typing import Any, Literal, Protocol
from ._style import AuthoringError, Length, Theme
from ._tree import _Child

# A typing view of the existing native compiled document, not a runtime wrapper.
class _PreparedDocument(Protocol):
    def stats(self) -> dict[str, Any]: ...
    def render_pdf(self, deterministic_hash: str | None = ...) -> bytes: ...
    def render_image_pages(self, dpi: int = ...) -> list[bytes]: ...
    def export_render_time_pagination_trace(self) -> dict[str, Any]: ...

@dataclass(frozen=True)
class Page:
    size: str | tuple[Length, Length] = ...
    margin: Length | tuple[Length, ...] = ...
    landscape: bool = ...
    def to_css(self) -> str: ...

@dataclass(frozen=True)
class Source:
    node_id: str
    path: tuple[str, ...]
    file: str | None
    line: int | None

class LayoutError(AuthoringError):
    page: int
    sources: tuple[Source, ...]
    reason: str | None
    failure_sources: tuple[Source, ...]
    def __init__(self, message: str, *, page: int, sources: Iterable[Source] = ...,
                 reason: str | None = ..., failure_sources: Iterable[Source] = ...,
                 code: str = ..., path: Iterable[str] = ...) -> None: ...
    def at(self, name: str) -> LayoutError: ...
    def to_dict(self) -> dict[str, Any]: ...

@dataclass(frozen=True)
class DocumentSource:
    html: str
    css: str
    sources: tuple[Source, ...]
    @property
    def a11y_report(self) -> dict[str, Any] | None: ...

@dataclass(frozen=True, init=False)
class Document:
    children: tuple[_Child, ...]
    title: str
    lang: str
    page: Page
    theme: Theme
    def __init__(self, *children: _Child, title: str = ..., lang: str = ...,
                 page: Page | None = ..., theme: Theme | None = ...) -> None: ...
    def compile(self, *, a11y_mode: Literal["warn", "raise"] | None = ...) -> DocumentSource: ...
    @property
    def required_tokens(self) -> tuple[str, ...]: ...
    def to_html(self, *, a11y_mode: Literal["warn", "raise"] | None = ...) -> str: ...
    def to_css(self, *, a11y_mode: Literal["warn", "raise"] | None = ...) -> str: ...
    def prepare(self, renderer: Renderer, *, a11y_mode: Literal["warn", "raise"] | None = ...) -> _PreparedDocument: ...
    def render_pdf(self, renderer: Renderer, *, a11y_mode: Literal["warn", "raise"] | None = ...) -> bytes: ...
    def render_image_pages(self, renderer: Renderer, *, dpi: int = ..., a11y_mode: Literal["warn", "raise"] | None = ...) -> list[bytes]: ...
    def emit_artifacts(self, *, html_path: str | PathLike[str], css_path: str | PathLike[str],
                       a11y_mode: Literal["warn", "raise"] | None = ...) -> None: ...

class Renderer:
    def __init__(self, **engine_options: Any) -> None: ...
    def engine_for(self, document: Document) -> Any: ...
    def checked_engine_for(self, document: Document, plan: DocumentSource) -> Any: ...
'''
    bridge = HEADER + '''from ..core import Element
from ._style import Theme
from ._tree import Node

def to_legacy(node: Node, *, theme: Theme | None = ...) -> tuple[Element | str, ...]: ...
'''
    return {"_style.pyi": style, "_tree.pyi": tree, "_table.pyi": table,
            "_document.pyi": document, "_bridge.pyi": bridge}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when a bundled stub differs from the generated contract")
    args = parser.parse_args()
    stale = []
    for name, text in generated_files().items():
        destination = PACKAGE / name
        if args.check:
            if not destination.is_file() or destination.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            destination.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("Regenerate component stubs with python tools/generate_component_stubs.py: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Component type stubs " + ("match the shared schema" if args.check else "generated"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
