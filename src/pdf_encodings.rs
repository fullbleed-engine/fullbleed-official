fn decode(table: &[u16; 256], byte: u8) -> Option<char> {
    let value = table[usize::from(byte)];
    (value != 0)
        .then(|| char::from_u32(u32::from(value)))
        .flatten()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn canonical_pdf_encoding_points_are_stable() {
        assert_eq!(standard_encoding_byte(b'A'), Some('A'));
        assert_eq!(mac_roman_encoding_byte(0x80), Some('\u{00c4}'));
        assert_eq!(win_ansi_encoding_byte(0x80), Some('\u{20ac}'));
        assert_eq!(pdf_doc_encoding_byte(0x80), Some('\u{2022}'));
        assert_eq!(standard_encoding_byte(0), None);
    }
}
